fn mat20_exp(a: &[[f64; 20]; 20]) -> [[f64; 20]; 20] {
    // Scaling-and-squaring: exp(A) = (exp(A / 16))^16 via 10-term Taylor series
    let scale = 1.0_f64 / 16.0_f64;
    let mut m = [[0.0_f64; 20]; 20];
    for i in 0..20 {
        for j in 0..20 {
            m[i][j] = a[i][j] * scale;
        }
    }
    let mut sum = [[0.0_f64; 20]; 20];
    let mut term = [[0.0_f64; 20]; 20];
    for i in 0..20 {
        sum[i][i] = 1.0;
        term[i][i] = 1.0;
    }
    for k in 1..=10 {
        term = mat20_mul(&term, &m);
        let inv_k = 1.0 / (k as f64);
        for i in 0..20 {
            for j in 0..20 {
                term[i][j] *= inv_k;
                sum[i][j] += term[i][j];
            }
        }
    }
    for _ in 0..4 {
        sum = mat20_mul(&sum, &sum);
    }
    sum
}

