#[inline]
pub fn aa_byte_to_state_and_mask(byte: u8) -> (i8, u32) {
    match byte.to_ascii_uppercase() {
        b'A' => (0, 1 << 0),
        b'C' => (1, 1 << 1),
        b'D' => (2, 1 << 2),
        b'E' => (3, 1 << 3),
        b'F' => (4, 1 << 4),
        b'G' => (5, 1 << 5),
        b'H' => (6, 1 << 6),
        b'I' => (7, 1 << 7),
        b'K' => (8, 1 << 8),
        b'L' => (9, 1 << 9),
        b'M' => (10, 1 << 10),
        b'N' => (11, 1 << 11),
        b'P' => (12, 1 << 12),
        b'Q' => (13, 1 << 13),
        b'R' => (14, 1 << 14),
        b'S' => (15, 1 << 15),
        b'T' => (16, 1 << 16),
        b'V' => (17, 1 << 17),
        b'W' => (18, 1 << 18),
        b'Y' => (19, 1 << 19),
        // Standard IUPAC amino-acid ambiguities
        b'B' => (-1, (1 << 2) | (1 << 11)), // D or N
        b'Z' => (-1, (1 << 3) | (1 << 13)), // E or Q
        b'J' => (-1, (1 << 7) | (1 << 9)),  // I or L
        _ => (-1, ALL_AA_MASK),
    }
}

/// Auto-detect whether `seqs` is an amino-acid alignment rather than a nucleotide alignment.
/// Amino-acid-exclusive letters `{E, F, I, L, P, Q, Z, J, O}` never appear in IUPAC DNA/RNA.
pub fn is_protein_alignment(seqs: &[String]) -> bool {
    let mut non_gap = 0usize;
    let mut aa_exclusive = 0usize;
    let mut acgtu = 0usize;
    for s in seqs.iter().take(64) {
        for &b in s.as_bytes().iter().take(4096) {
            let up = b.to_ascii_uppercase();
            if matches!(up, b'-' | b'?' | b'.' | b'*' | b'X' | b'N') {
                continue;
            }
            non_gap += 1;
            if matches!(up, b'E' | b'F' | b'I' | b'L' | b'P' | b'Q' | b'Z' | b'J' | b'O') {
                aa_exclusive += 1;
            } else if matches!(up, b'A' | b'C' | b'G' | b'T' | b'U') {
                acgtu += 1;
            }
        }
    }
    if non_gap == 0 {
        return false;
    }
    (aa_exclusive as f64 / non_gap as f64) > 0.02 || (acgtu as f64 / non_gap as f64) < 0.65
}

/// Translate aligned in-frame nucleotide coding sequences into canonical single-letter amino-acid sequences.
pub fn translate_coding_alignment(seqs: &[String]) -> Result<Vec<String>, String> {
    if seqs.is_empty() {
        return Err("Empty alignment cannot be translated.".to_string());
    }
    let l = seqs[0].len();
    let n_codons = l / 3;
    if n_codons == 0 {
        return Err("Alignment shorter than 1 codon (< 3 bp).".to_string());
    }
    let mut aa_seqs = Vec::with_capacity(seqs.len());
    for s in seqs {
        let bytes = s.as_bytes();
        let mut out = Vec::with_capacity(n_codons);
        for c in 0..n_codons {
            let base_to_i8 = |ch: u8| -> i8 {
                match ch.to_ascii_uppercase() {
                    b'A' => 0,
                    b'C' => 1,
                    b'G' => 2,
                    b'T' | b'U' => 3,
                    _ => -1,
                }
            };
            let b0 = bytes.get(3 * c).copied().unwrap_or(b'-');
            let b1 = bytes.get(3 * c + 1).copied().unwrap_or(b'-');
            let b2 = bytes.get(3 * c + 2).copied().unwrap_or(b'-');
            if b0 == b'-' && b1 == b'-' && b2 == b'-' {
                out.push(b'-');
            } else {
                let aa = translate_bases(base_to_i8(b0), base_to_i8(b1), base_to_i8(b2));
                if aa == b'*' {
                    out.push(b'-');
                } else {
                    out.push(aa);
                }
            }
        }
        aa_seqs.push(String::from_utf8(out).unwrap_or_default());
    }
    Ok(aa_seqs)
}

pub fn encode_protein_alignment(seqs: &[String]) -> (Vec<i8>, Vec<u32>, Vec<i8>, usize, usize) {
    let n = seqs.len();
    let l = seqs.first().map(|s| s.len()).unwrap_or(0);
    let mut mat = vec![-1_i8; n * l];
    let mut bitmasks = vec![ALL_AA_MASK; n * l];
    let mut counts = vec![[0_u32; AA_ALPHABET_SIZE]; l];

    for (i, s) in seqs.iter().enumerate() {
        let row_off = i * l;
        for (j, &byte) in s.as_bytes().iter().take(l).enumerate() {
            let (st, mask) = aa_byte_to_state_and_mask(byte);
            mat[row_off + j] = st;
            bitmasks[row_off + j] = mask;
            if st >= 0 {
                counts[j][st as usize] += 1;
            }
        }
    }

    let mut majority_state = vec![0_i8; l];
    for j in 0..l {
        let mut best_a = 0_i8;
        let mut best_c = counts[j][0];
        for a in 1..AA_ALPHABET_SIZE {
            if counts[j][a] > best_c {
                best_c = counts[j][a];
                best_a = a as i8;
            }
        }
        majority_state[j] = best_a;
    }

    (mat, bitmasks, majority_state, n, l)
}

#[inline]
fn median_f64(vals: &mut [f64]) -> f64 {
    if vals.is_empty() {
        return 0.0;
    }
    vals.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let mid = vals.len() / 2;
    if vals.len() % 2 == 1 {
        vals[mid]
    } else {
        0.5 * (vals[mid - 1] + vals[mid])
    }
}

