/// Pure IEEE-754 branchless `ln(x)` for positive `f32` (`x >= 1e-37`), accurate to `< 1 ULP`
/// with zero `libm`/`errno` side effects so LLVM vectorizes inner site loops cleanly.
#[inline(always)]
fn ln_f32_noerrno(x: f32) -> f32 {
    let xc = x.max(1e-37_f32);
    let bits = xc.to_bits();
    let raw_exp = ((bits >> 23) as i32) - 127;
    let m0 = f32::from_bits((bits & 0x007f_ffff) | 0x3f80_0000);
    let gt = (m0 > std::f32::consts::SQRT_2) as i32;
    let e = (raw_exp + gt) as f32;
    let m = if gt != 0 { 0.5_f32 * m0 } else { m0 };
    let u = (m - 1.0_f32) / (m + 1.0_f32);
    let u2 = u * u;
    let poly = 2.0_f32
        * u
        * (1.0_f32
            + u2 * (0.333_333_34_f32
                + u2 * (0.2_f32 + u2 * (0.142_857_15_f32 + u2 * 0.111_111_11_f32))));
    e * std::f32::consts::LN_2 + poly
}

#[inline]
fn lg08_trans_mat_aug(tau: f32) -> [[f32; 21]; 20] {
    let mut e_lam = [0.0_f64; 20];
    let tau64 = tau as f64;
    for r in 0..20 {
        e_lam[r] = (LG08_EVALS[r] * tau64).exp();
    }
    let mut out = [[1.0_f32; 21]; 20];
    for a in 0..20 {
        for b in 0..20 {
            let mut s = 0.0_f64;
            for r in 0..20 {
                s += LG08_EVEC_RINV[a][r] * e_lam[r] * LG08_EVEC_W[r][b];
            }
            out[a][b] = (s as f32).max(1e-30_f32);
        }
        out[a][20] = 1.0_f32;
    }
    out
}

